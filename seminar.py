# тестов используем модуль `stats` из библиотеки SciPy.

# %%
from scipy import stats

# %% [markdown]
# Выберем два столбца и удалим строки, в которых хотя бы одно из этих значений
# пропущено. Это важно: температура и осадки должны относиться к одному дню.

# %%
paired = weather[["tavg", "prcp"]].dropna()
paired.shape

# %% [markdown]
# Выберем два столбца. Их значения расположены в одном порядке: температура
# и осадки с одинаковым индексом относятся к одной дате.

# %%
temperature = paired["tavg"]
precipitation = paired["prcp"]

# %% [markdown]
# `stats.pearsonr()` вычисляет корреляцию Пирсона — меру линейной связи от −1
# до 1 — и p-value для проверки нулевой гипотезы об отсутствии корреляции.
# Значение около нуля означает слабую линейную связь, но не обязательно
# отсутствие любой связи.

# %%
correlation = stats.pearsonr(temperature, precipitation)
correlation

