# %% [markdown]
# ### Несколько графиков на одной фигуре
#
# Разместим температуру и осадки друг под другом. `plt.subplots(2, 1)`
# создаёт две области графиков в одном столбце, а `sharex=True` объединяет
# ось дат. Настроим цвет, толщину линии, прозрачность и сетку.

# %%
fig, (ax_temp, ax_rain) = plt.subplots(2, 1, figsize=(10, 6), sharex=True)

ax_temp.plot(weather.index, weather["tavg"], color="tomato", linewidth=1.5)
ax_temp.axhline(0, color="gray", linestyle="--", linewidth=1)
ax_temp.set_title("Погода в Москве в 2025 году")
ax_temp.set_ylabel("Температура, °C")
ax_temp.grid(alpha=0.3)

ax_rain.bar(weather.index, weather["prcp"], color="steelblue", alpha=0.7)
ax_rain.set_ylabel("Осадки, мм")
ax_rain.set_xlabel("Дата")
ax_rain.grid(alpha=0.3)

plt.tight_layout()
plt.show()

