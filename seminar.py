# Добавим список названий месяцев в том же порядке.

# %%
months = ["Январь", "Февраль", "Март", "Апрель", "Май", "Июнь",
          "Июль", "Август", "Сентябрь", "Октябрь", "Ноябрь", "Декабрь"]

# %% [markdown]
# Можно перебрать индексы и взять элементы обоих списков по одному индексу.
# `range(12)` даёт числа от 0 до 11: верхняя граница не включается.

# %%
for i in range(12):
    print(f"{months[i]}: {temps[i]:.1f} °C")

# %% [markdown]
# Удобнее использовать `zip()`: она объединяет элементы списков попарно,
# поэтому обращаться к ним по индексам не нужно. Заодно причешем f-строке `<10` выравнивает текст по левому краю в поле шириной 10, а `>4.1f` — число по правому краю в поле шириной 4, с одним знаком после запятой.

# %%
for month, temp in zip(months, temps):
    print(f"{month:<10} {temp:>4.1f} °C")
# %% [markdown]
# Допустим, мы хотим посмотреть только летние месяцы или погоду в последние полгода.
# Для этого используем срез: `список[начало:конец]`. Элемент с индексом
# `начало` включается, а с индексом `конец` — нет. Июнь имеет индекс 5,
# поэтому срез `[5:8]` содержит июнь, июль и август.

# %%
for month, temp in zip(months[5:8], temps[5:8]):
    print(f"{month:<10} {temp:>4.1f} °C")

# %% [markdown]
# Если не указать конец среза, он продолжится до конца списка. Например,
# `[6:]` выбирает месяцы с июля по декабрь. Аналогично `[:6]` выбирает
# элементы с начала списка до индекса 6, не включая его.

# %%
for month, temp in zip(months[6:], temps[6:]):
    print(f"{month:<10} {temp:>4.1f} °C")

